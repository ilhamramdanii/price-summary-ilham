const buildSeries = (dates: string[], ohlcv: [number, number, number, number, number][]) =>
  Object.fromEntries(
    dates.map((date, i) => [
      date,
      {
        '1. open':   ohlcv[i][0].toFixed(4),
        '2. high':   ohlcv[i][1].toFixed(4),
        '3. low':    ohlcv[i][2].toFixed(4),
        '4. close':  ohlcv[i][3].toFixed(4),
        '5. volume': String(ohlcv[i][4]),
      },
    ])
  );

